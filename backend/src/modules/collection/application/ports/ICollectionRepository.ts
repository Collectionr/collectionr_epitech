import type { CardEntry } from '../../domain/entities/CardEntry';
import type { Collection } from '../../domain/entities/Collection';
import type { PageRequest } from '../../domain/value-objects/PageRequest';
import type { Page } from './Page';

export const COLLECTION_REPOSITORY = 'COLLECTION_REPOSITORY';

/**
 * Persistence of collections and of their card entries. One port for both: an entry only makes
 * sense inside its collection, and every entry operation is scoped by `collectionId` so that an
 * entry can never be reached through a collection it does not belong to.
 *
 * The use cases check ownership; this port does not know about authenticated users.
 */
export interface ICollectionRepository {
  /**
   * Insert or update — the id is generated by the domain, never by the repository.
   *
   * MUST reject with LicenceNotFoundError (application/errors/CollectionErrors.ts) when
   * `licenceTCGId` is not in the catalogue. The use cases do not check it first: only the foreign
   * key in the store guarantees it, including when the licence is removed in the meantime.
   */
  save(collection: Collection): Promise<Collection>;
  findById(id: string): Promise<Collection | null>;
  /** A user's collections, most recently created first, ties broken on the id so pages are stable. */
  findByUserId(userId: string, page: PageRequest): Promise<Page<Collection>>;
  /** How many collections the user owns (for the MAX_COLLECTIONS_PER_USER limit). */
  countByUserId(userId: string): Promise<number>;
  /**
   * Deletes the collection AND all its card entries, atomically: either both are gone or neither.
   * Does nothing when the collection does not exist.
   */
  delete(id: string): Promise<void>;

  /**
   * Insert or update — the id is generated by the domain, never by the repository.
   *
   * MUST reject with CardNotFoundError when `cardId` is not in the catalogue, or when `variantId`
   * is not a printing of that card (a variant always belongs to a card, documentation-metier.md).
   * MUST reject with CollectionNotFoundError when the collection no longer exists (deleted by a
   * concurrent request). Both are guaranteed by foreign keys, not by a read-then-write.
   */
  saveCardEntry(entry: CardEntry): Promise<CardEntry>;
  /** Null when the entry does not exist OR belongs to another collection. */
  findCardEntryById(collectionId: string, entryId: string): Promise<CardEntry | null>;
  /**
   * A collection's entries, most recently added first, ties broken on the id so pages are stable.
   * Must stay fast on 10 000 entries (CDC §3.1.3): index on the collection, never load them all.
   */
  findCardEntries(collectionId: string, page: PageRequest): Promise<Page<CardEntry>>;
  /** Does nothing when the entry does not exist in that collection. */
  deleteCardEntry(collectionId: string, entryId: string): Promise<void>;
}
